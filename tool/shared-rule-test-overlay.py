# Test-only generated host overlay, never modifies tracked product Kotlin.
from pathlib import Path
import sys,hashlib,json
out=Path(sys.argv[2]);out.mkdir(parents=True,exist_ok=True)
source=Path('tool/android-native/main/DeviceProofHost.kt')
host=Path('android/app/src/main/kotlin/app/otpanda/DeviceProofHost.kt')
gradle=Path('android/app/build.gradle.kts')
needle=b'const val STEP_UP_ENABLED = false'
if sys.argv[1]=='apply':
 assert source.read_bytes().count(needle)==1
 assert host.read_bytes()==source.read_bytes()
 assert b'applicationId = "app.otpanda"' in gradle.read_bytes()
 for name,p in [('host',host),('gradle',gradle)]: (out/(name+'.original')).write_bytes(p.read_bytes())
 meta={'tracked_sha256':hashlib.sha256(source.read_bytes()).hexdigest()};(out/'overlay.json').write_text(json.dumps(meta))
 host.write_bytes(host.read_bytes().replace(needle,b'const val STEP_UP_ENABLED = true',1))
 gradle.write_bytes(gradle.read_bytes().replace(b'applicationId = "app.otpanda"',b'applicationId = "app.otpanda.sharedfixture"',1))
 assert host.read_bytes().count(b'const val STEP_UP_ENABLED = true')==1
 print('TEST_ONLY_STEPUP_OVERLAY disposable app.otpanda.sharedfixture; tracked host unchanged')
else:
 for name,p in [('host',host),('gradle',gradle)]:p.write_bytes((out/(name+'.original')).read_bytes());assert p.read_bytes()==(out/(name+'.original')).read_bytes()
 assert hashlib.sha256(source.read_bytes()).hexdigest()==json.loads((out/'overlay.json').read_text())['tracked_sha256']
 assert source.read_bytes()==host.read_bytes() and source.read_bytes().count(needle)==1
 print('TEST_ONLY_STEPUP_OVERLAY_RESTORED tracked false, generated bytes exact')
